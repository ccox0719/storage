const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const root=path.join(__dirname,'..');
const data=JSON.parse(fs.readFileSync(path.join(root,'data/lutron-radiora2.json')));
assert.equal(data.equipment.length,110);
assert.equal(new Set(data.equipment.map(e=>e.id)).size,110);
assert.deepEqual([...new Set(data.equipment.map(e=>e.page))],Array.from({length:79},(_,i)=>i+2));
assert.equal(data.keypads.length,12);
assert.equal(data.keypads.reduce((n,k)=>n+k.buttons.length,0),34);
assert.equal(data.keypads.flatMap(k=>k.buttons).flatMap(b=>b.actions).length,198);
assert.ok([...data.equipment,...data.zones,...data.keypads].every(e=>e.status==='documented' && e.verified===false));
assert.ok(data.keypads.every(k=>k.save_on_hold==='Disabled'));
assert.equal(data.equipment.find(e=>e.model==='CONNECT-BDG2-1').page,75);
assert.equal(data.equipment.filter(e=>e.kind==='remote dimmer').flatMap(e=>e.reported_zones).length,0);
assert.equal(data.equipment.flatMap(e=>e.accessories).filter(m=>m==='PHPM-PA-120-WH').length,2);
assert.equal(data.equipment.find(e=>e.id==='install-08-2').notes,'*Zone attached:\nKITCHEN > WEST WALL\nKITCHEN > KITCHEN\nLIGHTS');
assert.equal(data.keypads[0].buttons.find(b=>b.label==='Off').actions.find(a=>a.target.endsWith('LIVING ROOM FAN')).fan_speed,'High');
const bedroom=data.keypads.find(k=>k.model==='RR-T5RL-MN');
assert.equal(bedroom.buttons.find(b=>b.label==='ALL OFF').actions.find(a=>a.target.endsWith('LIVING ROOM FAN')).fan_speed,'Off');
assert.equal(bedroom.buttons.some(b=>b.label==='SONOS ON'),false);
assert.equal(data.keypads.find(k=>k.path.endsWith('GARAGE MUSIC')).buttons.length,0);
const ctx={document:{addEventListener(){}},esc:s=>String(s).replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('"','&quot;')};
vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(root,'js/lutron-data.js'),'utf8')+'\nthis.data=LUTRON_DATA',ctx);
assert.equal(JSON.stringify(ctx.data),JSON.stringify(data));
vm.runInContext(fs.readFileSync(path.join(root,'js/lutron.js'),'utf8'),ctx);
const html=ctx.renderLutronReference();
assert.ok(html.includes('physically unverified'));
ctx.data.keypads[0].path='<img src=x onerror=alert(1)>';
assert.ok(!ctx.renderLutronReference().includes('<img src=x'));
assert.ok(ctx.renderLutronReference().includes('&lt;img'));
console.log('Lutron data integrity, provenance, command distinctions, and HTML escaping passed.');
